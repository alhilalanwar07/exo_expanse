    /**
     * Generate both the Livewire component class and the Blade view for a theme.
     */
    public function generate(Theme $theme): void
    {
        $this->generateComponentClass($theme);
        $this->generateBladeView($theme);

        // Update theme's view_file to point to the generated view
        $theme->update(['view_file' => 'themes.' . $theme->slug]);
    }

    /**
     * Generate Livewire component class (follows AdatBone.php pattern).
     */
    public function generateComponentClass(Theme $theme): string
    {
        $className = Str::studly($theme->slug);
        $viewName = 'livewire.themes.' . $theme->slug;
        $filePath = app_path("Livewire/Themes/{$className}.php");

        // Don't overwrite if manually created
        if (file_exists($filePath) && !$this->isGenerated($filePath)) {
            return $filePath;
        }

