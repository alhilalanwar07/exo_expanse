    /**
     * Re-generate Blade view (e.g., after sections config update).
     */
    public function regenerateBladeView(Theme $theme): void
    {
        $this->generateBladeView($theme);
    }

    /**
     * Delete generated theme files.
     */
    public function deleteThemeFiles(Theme $theme): void
    {
        $className = Str::studly($theme->slug);
        $phpPath = app_path("Livewire/Themes/{$className}.php");
        $bladePath = resource_path("views/livewire/themes/{$theme->slug}.blade.php");

        if (file_exists($phpPath) && $this->isGenerated($phpPath)) {
            unlink($phpPath);
        }

        if (file_exists($bladePath) && $this->isGenerated($bladePath)) {
            unlink($bladePath);
        }
    }

    /**
     * Check if a file was auto-generated (has our marker comment).
     */
    private function isGenerated(string $filePath): bool
    {
        $content = file_get_contents($filePath);

        return str_contains($content, 'AUTO-GENERATED by ThemeGeneratorService');
    }

