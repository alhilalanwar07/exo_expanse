<script>
function bugisTheme(targetTimestamp) {
    return {
        isOpened: false,
        isPlaying: false,
        menuCollapsed: true,
        autoScrolling: false,
        autoScrollCollapsed: true,
        scrollSpeed: 1,
        autoScrollInterval: null,
        hasAutoScrolledOnce: false,
        lightboxOpen: false,
        lightboxImg: '',
        toastShow: false,
        toastMessage: '',
        days: 0,
        hours: 0,
        minutes: 0,
        seconds: 0,
        targetTime: targetTimestamp * 1000,

        init() {
            document.body.classList.add('stop-scrolling');
            this.updateCountdown();
            setInterval(() => {
                this.updateCountdown();
            }, 1000);
            this.initVideoReplay();
        },

        openInvitation() {
            this.isOpened = true;
            document.body.classList.remove('stop-scrolling');
            
            // Animate cover slide up
            const coverEl = document.getElementById('cover');
            if (coverEl) {
                coverEl.classList.add('cover-hidden');
            }

            // Start background music
            this.playMusic();

            // Start Hero video
            const heroVideo = document.getElementById('heroVideo');
            if (heroVideo) {
                heroVideo.currentTime = 0;
                heroVideo.play().catch(e => console.log('Video autoplay error:', e));
            }

            // Show motion text
            setTimeout(() => {
                const motionText = document.querySelector('.motionText');
                if (motionText) {
                    motionText.style.display = 'flex';
                }
            }, 1200);

            // Safety fallback: if video ended event is delayed, start auto-scroll after 20.5s
            setTimeout(() => {
                if (this.isOpened && !this.autoScrolling && !this.hasAutoScrolledOnce) {
                    this.hasAutoScrolledOnce = true;
                    this.autoScrolling = true;
                    this.startScroll();
                    this.showToast('Auto scroll aktif');
                }
            }, 20500);

            // Scroll into hero
            this.scrollTo('.motionSection');
        },

        playMusic() {
            const audio = document.getElementById('song');
            if (audio) {
                audio.play().then(() => {
                    this.isPlaying = true;
                }).catch(e => console.log('Audio error:', e));
            }
        },

        pauseMusic() {
            const audio = document.getElementById('song');
            if (audio) {
                audio.pause();
                this.isPlaying = false;
            }
        },

        toggleMusic() {
            if (this.isPlaying) {
                this.pauseMusic();
            } else {
                this.playMusic();
            }
        },

        initVideoReplay() {
            // Video replay & auto-scroll upon animation completion:
            // "auto otomatis jika animasi telah selesai di play dan menu secara default collapse disamping"
            const heroVideo = document.getElementById('heroVideo');
            const heroSection = document.querySelector('.motionSection');
            if (!heroVideo || !heroSection) return;

            // Ensure video does NOT loop endlessly in-place
            heroVideo.loop = false;

            // Trigger auto-scroll automatically when hero video animation finishes
            heroVideo.addEventListener('ended', () => {
                console.log('Hero animation ended -> starting auto-scroll automatically');
                this.autoScrolling = true;
                this.startScroll();
                this.showToast('Auto scroll aktif');
            });

            // Also support timeupdate check if browser doesn't dispatch ended event cleanly
            heroVideo.addEventListener('timeupdate', () => {
                if (heroVideo.duration && heroVideo.currentTime >= (heroVideo.duration - 0.4)) {
                    if (!this.autoScrolling && this.isOpened && !this.hasAutoScrolledOnce) {
                        this.hasAutoScrolledOnce = true;
                        this.autoScrolling = true;
                        this.startScroll();
                        this.showToast('Auto scroll aktif');
                    }
                }
            });

            let hasLeftHero = false;

            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (!entry.isIntersecting) {
                        // Scrolled away from hero video
                        hasLeftHero = true;
                        heroVideo.pause();
                    } else {
                        // Returned to hero video!
                        if (hasLeftHero) {
                            hasLeftHero = false;
                            heroVideo.currentTime = 0;
                            heroVideo.play().catch(e => console.log('Replay error:', e));
                        }
                    }
                });
            }, { threshold: 0.25 });

            observer.observe(heroSection);
        },

        scrollTo(selector) {
            const el = document.querySelector(selector);
            if (el) {
                el.scrollIntoView({ behavior: 'smooth', block: 'start' });
            }
        },

        toggleAutoScroll() {
            this.autoScrolling = !this.autoScrolling;
            if (this.autoScrolling) {
                this.startScroll();
            } else {
                this.stopScroll();
            }
        },

        startScroll() {
            this.stopScroll();
            const step = () => {
                if (!this.autoScrolling) return;
                const distance = 1.2 * this.scrollSpeed;
                window.scrollBy({ top: distance, behavior: 'instant' });
                if ((window.innerHeight + window.scrollY) >= document.documentElement.scrollHeight - 10) {
                    this.autoScrolling = false;
                    return;
                }
                this.autoScrollInterval = requestAnimationFrame(step);
            };
            this.autoScrollInterval = requestAnimationFrame(step);
        },

        stopScroll() {
            if (this.autoScrollInterval) {
                cancelAnimationFrame(this.autoScrollInterval);
                this.autoScrollInterval = null;
            }
        },

        cycleScrollSpeed() {
            if (this.scrollSpeed === 1) this.scrollSpeed = 2;
            else if (this.scrollSpeed === 2) this.scrollSpeed = 3;
            else this.scrollSpeed = 1;
        },

        openLightbox(url) {
            this.lightboxImg = url;
            this.lightboxOpen = true;
        },

        copyFromContent(el) {
            let content = '';
            const parent = el.closest('.elementor-widget-weddingpress-copy-text');
            if (parent) {
                const copyDiv = parent.querySelector('.copy-content');
                if (copyDiv) content = copyDiv.innerText.trim();
            }
            if (!content) {
                const prev = el.previousElementSibling;
                if (prev) content = prev.innerText.trim();
            }
            if (content) {
                this.copyToClipboard(content);
            }
        },

        copyToClipboard(text) {
            navigator.clipboard.writeText(text).then(() => {
                this.showToast('Berhasil disalin: ' + text);
            }).catch(() => {
                this.showToast('Gagal menyalin');
            });
        },

        showToast(msg) {
            this.toastMessage = msg;
            this.toastShow = true;
            setTimeout(() => {
                this.toastShow = false;
            }, 2500);
        },

        updateCountdown() {
            const now = new Date().getTime();
            const distance = this.targetTime - now;
            if (distance < 0) {
                this.days = 0;
                this.hours = 0;
                this.minutes = 0;
                this.seconds = 0;
                return;
            }
            this.days = Math.floor(distance / (1000 * 60 * 60 * 24));
            this.hours = Math.floor((distance % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
            this.minutes = Math.floor((distance % (1000 * 60 * 60)) / (1000 * 60));
            this.seconds = Math.floor((distance % (1000 * 60)) / 1000);
        }
    };
}
</script>
